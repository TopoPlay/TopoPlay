"""Record explicit per-machine build dependencies; no Downloads default."""
from pathlib import Path
import argparse,json,os,shlex,subprocess,sys
from topoplay_paths import root

def framework(path):return (path/'libs/openFrameworksCompiled/project/makefileCommon/compile.project.mk').is_file()
def freenect(path,build=None,lib=None):
    path=path.expanduser().resolve();build=Path(build).expanduser().resolve() if build else path/'build';lib=Path(lib).expanduser().resolve() if lib else build/'lib'
    if (path/'include/libfreenect2/libfreenect2.hpp').is_file() and (build/'libfreenect2/config.h').is_file() and any(lib.glob('libfreenect2.so*')):return path,build,lib
    return None

def resolve_dependencies(project,of_root=None,freenect_root=None,freenect_build=None,freenect_lib=None):
    project=Path(project).resolve();saved={};record=project/'topoplay-build.json'
    if record.is_file():saved=json.loads(record.read_text())
    requested=of_root or os.environ.get('OF_ROOT') or saved.get('of_root')
    of=Path(requested).expanduser().resolve() if requested else next((p for p in project.parents if framework(p)),None)
    if of is None or not framework(of):raise RuntimeError('Specify the openFrameworks folder: python3 scripts/configure.py --of-root /path/to/openFrameworks')
    requested=freenect_root or os.environ.get('FREENECT2_ROOT') or saved.get('freenect2_root')
    build=freenect_build or os.environ.get('FREENECT2_BUILD') or saved.get('freenect2_build')
    lib=freenect_lib or os.environ.get('FREENECT2_LIB_DIR') or saved.get('freenect2_lib_dir')
    found=freenect(Path(requested),build,lib) if requested else None
    pkg=False
    if requested and not found:raise RuntimeError('libfreenect2 source/generated headers/library not found at the specified paths.')
    if not found:
        try:pkg=subprocess.run(['pkg-config','--exists','libfreenect2'],check=False).returncode==0
        except FileNotFoundError:pass
    if not found and not pkg:
        # Bounded sibling discovery helps existing developer layouts without
        # assuming what their parent folder is called. Explicit flags win.
        for parent in [project.parent,of.parent]:
            for candidate in sorted(parent.glob('libfreenect2*'))[:32]:
                found=freenect(candidate)
                if found:break
            if found:break
    if not found and not pkg:raise RuntimeError('libfreenect2 not detected. Run configure.py with --freenect2-root /path/to/libfreenect2, or install its pkg-config metadata.')
    values={'of_root':str(of),'freenect2_pkg_config':pkg and not found}
    if found:values.update(zip(['freenect2_root','freenect2_build','freenect2_lib_dir'],map(str,found)))
    # OF make treats include paths as whitespace-separated lists. This limit
    # applies only to BUILD paths; installed application paths may contain spaces.
    for value in [str(project),str(of),*[str(v) for v in (found or [])]]:
        if any(c.isspace() or c in '#$:\\' for c in value):raise RuntimeError('openFrameworks build paths cannot contain spaces or make-special characters. Choose a simple source/dependency path; the installed app can use spaces.')
    return values

def configure(project,of_root=None,freenect_root=None,freenect_build=None,freenect_lib=None):
    project=Path(project).resolve()
    values=resolve_dependencies(project,of_root,freenect_root,freenect_build,freenect_lib)
    of=Path(values['of_root'])
    found=tuple(values[k] for k in ('freenect2_root','freenect2_build','freenect2_lib_dir')) if 'freenect2_root' in values else None
    (project/'topoplay-build.json').write_text(json.dumps(values,indent=2)+'\n')
    lines=['# Generated by TopoPlay configure.py; machine-local, do not distribute.','OF_ROOT := '+str(of)]
    if found:lines += ['FREENECT2_ROOT := '+str(found[0]),'FREENECT2_BUILD := '+str(found[1]),'FREENECT2_LIB_DIR := '+str(found[2])]
    (project/'config.local.make').write_text('\n'.join(lines)+'\n')
    print('TopoPlay build paths recorded in '+str(project/'topoplay-build.json'))
    return values

def main():
    a=argparse.ArgumentParser(description=__doc__);a.add_argument('--of-root');a.add_argument('--freenect2-root');a.add_argument('--freenect2-build');a.add_argument('--freenect2-lib-dir');args=a.parse_args()
    configure(root(),args.of_root,args.freenect2_root,args.freenect2_build,args.freenect2_lib_dir)
if __name__=='__main__':
    try:main()
    except (RuntimeError,OSError) as e:sys.exit('STOP: '+str(e))
